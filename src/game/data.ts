function makePrompts(seeds: SeedPrompt[], difficulty: Difficulty, offset: number): Prompt[] {
  return seeds.map(([text, reading, category], index) => ({
    id: `${difficulty}-${offset + index + 1}`,
    text: stripFinalPunctuation(text),
    reading: stripFinalPunctuation(reading),
    category,
    difficulty,
  }));
}

function withVariants(seeds: SeedPrompt[]): SeedPrompt[] {
  return seeds.map(([text, reading, category]) => [`${text}ね`, `${reading}ね`, category]);
}

function stripFinalPunctuation(value: string): string {
  return value.replace(/[。．.!！?？]+$/u, '');
}

